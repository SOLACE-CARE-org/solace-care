// Copies what the staff login theme needs into solace-staff/login/resources/generated (git-ignored):
// the design tokens as CSS, the two typefaces (self-hosted, no font CDN) and the logo.
import { copyFileSync, mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const out = resolve(here, "solace-staff/login/resources/generated");
mkdirSync(join(out, "fonts"), { recursive: true });

copyFileSync(resolve(here, "../../../packages/tokens/dist/tokens.css"), join(out, "tokens.css"));

// The Latin subset covers English and French (é, è, à, ç, œ ...).
const faces = [
  ["Figtree", "@fontsource/figtree", "figtree", [400, 500, 600, 700]],
  ["Bricolage Grotesque", "@fontsource/bricolage-grotesque", "bricolage-grotesque", [500, 600, 700]],
];
let css = "/* Generated by infra/keycloak/themes/build.mjs from @fontsource packages. */\n";
for (const [family, pkg, id, weights] of faces) {
  const dir = join(dirname(require.resolve(`${pkg}/package.json`)), "files");
  for (const weight of weights) {
    for (const subset of ["latin"]) {
      const file = `${id}-${subset}-${weight}-normal.woff2`;
      copyFileSync(join(dir, file), join(out, "fonts", file));
      css += `@font-face { font-family: "${family}"; font-style: normal; font-weight: ${weight}; font-display: swap; src: url("fonts/${file}") format("woff2"); }\n`;
    }
  }
}
writeFileSync(join(out, "fonts.css"), css);

// STAND-IN until the splash lockup (Logos README) is supplied: the app icon, a light mark on
// exactly the brand-splash green of the left panel.
const logos = resolve(here, "../../../design/design-system/assets/Logos/png");
copyFileSync(join(logos, "solace-care-app-icon-512.png"), join(out, "lockup.png"));
copyFileSync(join(logos, "solace-care-app-icon-32.png"), join(out, "favicon.png"));
console.log("keycloak theme: generated assets ready");
