// Generates platform files from design/design-system/tokens.json (CLAUDE.md, Design: "generate
// platform files from tokens.json at build time; never retype a hex value or a size").
//
//   dist/tokens.ts   React Native: colors, space, radius, size, type styles, focus ring
//   dist/tokens.css  Admin portal: CSS custom properties with the design system's --names,
//                    plus one class per type style (.type-display-xl ...)
//
// Runs on install (prepare) and on `pnpm --filter @solace/tokens build`.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, "../../../design/design-system/tokens.json");
const out = resolve(here, "../dist");
const tokens = JSON.parse(readFileSync(source, "utf8"));

const px = (value) => {
  const match = /^(-?[\d.]+)px$/.exec(String(value).trim());
  if (!match) throw new Error(`Expected a px value, got ${value}`);
  return Number(match[1]);
};
const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

// --- read -----------------------------------------------------------------------------------

const colors = Object.fromEntries(tokens.color.tokens.map((t) => [t.name, t.value]));
const space = Object.fromEntries(tokens.spacing.tokens.map((t) => [t.name, px(t.value)]));
const radius = Object.fromEntries(tokens.radius.tokens.map((t) => [t.name, px(t.value)]));
const size = Object.fromEntries(tokens.size.tokens.map((t) => [t.name, px(t.value)]));
const shadows = Object.fromEntries(tokens.shadow.tokens.map((t) => [t.name, t.value]));

// Fonts are bundled from the @expo-google-fonts packages, one family name per weight.
const expoFamily = {
  display: { 500: "BricolageGrotesque_500Medium", 600: "BricolageGrotesque_600SemiBold", 700: "BricolageGrotesque_700Bold" },
  body: { 400: "Figtree_400Regular", 500: "Figtree_500Medium", 600: "Figtree_600SemiBold", 700: "Figtree_700Bold" },
};

const typeStyles = {};
for (const group of tokens.type.groups) {
  for (const style of group.styles) {
    const fontSize = px(style.fontSize);
    const weight = Number(style.fontWeight);
    const fontFamily = expoFamily[group.family][weight];
    if (!fontFamily) throw new Error(`No bundled ${group.family} font for weight ${weight}`);
    typeStyles[style.name] = {
      family: group.family,
      fontFamily,
      fontSize,
      lineHeight: Math.round(fontSize * Number(style.lineHeight) * 100) / 100,
      lineHeightRatio: Number(style.lineHeight),
      fontWeight: weight,
      letterSpacing: style.letterSpacing ? px(style.letterSpacing) : 0,
    };
  }
}

// --- React Native ---------------------------------------------------------------------------

const header = `// Generated by packages/tokens/scripts/build.mjs from design/design-system/tokens.json.\n// Do not edit: change tokens.json and rebuild.\n`;
const object = (o) =>
  `{\n${Object.entries(o)
    .map(([k, v]) => `  ${JSON.stringify(camel(k))}: ${JSON.stringify(v)},`)
    .join("\n")}\n}`;

const fontsToLoad = [...new Set(Object.values(expoFamily).flatMap((w) => Object.values(w)))];

const native = `${header}
export const colors = ${object(colors)} as const;

export const space = ${object(space)} as const;

export const radius = ${object(radius)} as const;

export const size = ${object(size)} as const;

/** Type styles for React Native. Use with <Text style={type.body}>; fontWeight is carried by the family. */
export const type = {
${Object.entries(typeStyles)
  .map(
    ([name, s]) =>
      `  ${JSON.stringify(camel(name))}: { fontFamily: ${JSON.stringify(s.fontFamily)}, fontSize: ${s.fontSize}, lineHeight: ${s.lineHeight}, letterSpacing: ${s.letterSpacing} },`,
  )
  .join("\n")}
} as const;

/** Bundled font per family and weight, for the few places a screen sets a weight outside a type style. */
export const fontFamily = ${JSON.stringify(expoFamily)} as const;

/** Every bundled font family the type styles use; load them all before first render. */
export const fontFamilies = ${JSON.stringify(fontsToLoad)} as const;

/** The only shadow: keyboard focus, a 2px white gap then a 2px brand ring. */
export const focusRing = { gap: 2, width: 2, gapColor: ${JSON.stringify(colors["on-brand"])}, color: ${JSON.stringify(colors.brand)} } as const;

export type ColorToken = keyof typeof colors;
export type TypeToken = keyof typeof type;
`;

// --- CSS --------------------------------------------------------------------------------------

const cssFamilies = {
  display: tokens.type.families.display,
  body: tokens.type.families.body,
};
const css = `/* Generated by packages/tokens/scripts/build.mjs from design/design-system/tokens.json.
   Do not edit: change tokens.json and rebuild. */
:root {
${Object.entries(colors).map(([k, v]) => `  --${k}: ${v};`).join("\n")}
${Object.entries(space).map(([k, v]) => `  --${k}: ${v}px;`).join("\n")}
${Object.entries(radius).map(([k, v]) => `  --${k}: ${v}px;`).join("\n")}
${Object.entries(size).map(([k, v]) => `  --${k}: ${v}px;`).join("\n")}
${Object.entries(shadows).map(([k, v]) => `  --${k}: ${v};`).join("\n")}
  --font-display: ${cssFamilies.display};
  --font-body: ${cssFamilies.body};
}
${Object.entries(typeStyles)
  .map(
    ([name, s]) =>
      `.type-${name} { font-family: var(--font-${s.family}); font-size: ${s.fontSize}px; line-height: ${s.lineHeightRatio}; font-weight: ${s.fontWeight};${s.letterSpacing ? ` letter-spacing: ${s.letterSpacing}px;` : ""} }`,
  )
  .join("\n")}
`;

mkdirSync(out, { recursive: true });
writeFileSync(resolve(out, "tokens.ts"), native);
writeFileSync(resolve(out, "tokens.css"), css);
console.log(
  `tokens: ${Object.keys(colors).length} colours, ${Object.keys(typeStyles).length} type styles -> packages/tokens/dist`,
);
